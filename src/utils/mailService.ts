import { Business, Customer, Invoice, KhataEntry, SmtpSettings } from '../types';
import { formatCurrency, formatDate } from './formatters';

export interface SendEmailPayload {
  to: string;
  subject: string;
  html: string;
  text?: string;
  smtpSettings: SmtpSettings;
}

export interface MailServiceResult {
  success: boolean;
  message: string;
  fallbackUrl?: string;
  usingFallback?: boolean;
}

/**
 * Builds a direct Gmail web compose URL as an immediate user fallback or preview
 */
export function buildGmailComposeUrl(to: string, subject: string, bodyText: string): string {
  const params = new URLSearchParams({
    view: 'cm',
    fs: '1',
    to,
    su: subject,
    body: bodyText,
  });
  return `https://mail.google.com/mail/?${params.toString()}`;
}

/**
 * Sends an email using the backend Express /api/mail/send endpoint configured with the user's SMTP credentials.
 * If the SMTP service is unconfigured or encounters an error, it provides a seamless fallback with a direct Gmail compose link.
 */
export async function sendEmailViaSmtp(payload: SendEmailPayload): Promise<MailServiceResult> {
  const { to, subject, html, text, smtpSettings } = payload;

  const senderEmail = smtpSettings.email?.trim() || '';

  // Validate sender email
  if (!senderEmail || !senderEmail.includes('@')) {
    const fallbackUrl = buildGmailComposeUrl(to, subject, text || '');
    return {
      success: false,
      message: 'Sender email is not configured in Settings. Please set your Gmail / business email in Store Settings.',
      fallbackUrl,
      usingFallback: true,
    };
  }

  try {
    const response = await fetch('/api/mail/send', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        smtp: {
          host: smtpSettings.host || 'smtp.gmail.com',
          port: smtpSettings.port || 465,
          secure: smtpSettings.secure !== false,
          user: senderEmail,
          pass: smtpSettings.appPassword || '',
          senderName: smtpSettings.senderName || 'VYAPRIX Business',
        },
        to,
        subject,
        html,
        text: text || '',
      }),
    });

    const data = await response.json();

    if (response.ok && data.success) {
      return {
        success: true,
        message: `Email sent successfully from ${senderEmail} to ${to}!`,
      };
    } else {
      // Backend returned failure or fallback
      const fallbackUrl = buildGmailComposeUrl(to, subject, text || '');
      return {
        success: false,
        message: data.message || data.error || 'SMTP delivery failed. Click below to send directly via Gmail.',
        fallbackUrl,
        usingFallback: true,
      };
    }
  } catch (err: any) {
    const fallbackUrl = buildGmailComposeUrl(to, subject, text || '');
    return {
      success: false,
      message: `Network error connecting to email server: ${err.message || 'Unknown error'}. Click below to open in Gmail.`,
      fallbackUrl,
      usingFallback: true,
    };
  }
}

